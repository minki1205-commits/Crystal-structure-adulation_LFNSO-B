"""Bundle completed results and portable rerun configs; preserve original data."""
from pathlib import Path
import hashlib
import json
import zipfile

root = Path(__file__).resolve().parents[1]
out = root/'03_structure_model_search'
archive = out/'LFNSO_occupational_search_results.zip'
files = []
for folder in ['occupational_search_02','occupational_search_03','occupational_assessment_03']:
    files += [(p,p.relative_to(root).as_posix()) for p in (out/folder).rglob('*') if p.is_file()]
for pattern in ['src/lfnso/*.py','tests/*.py','configs/occupational*.json']:
    files += [(p,p.relative_to(root).as_posix()) for p in root.glob(pattern)]
for name in ['pyproject.toml','requirements.lock.txt','README.md','docs/OCCUPATIONAL_SEARCH.md','docs/COMPOSITION_MODEL_SEARCH.md','scripts/package_occupational_results.py']:
    files.append((root/name,name))
files.extend([(Path('/workspace/lfnso-data/raw/Li2MnO3_C2M_JEMS.cif'),'inputs/Li2MnO3_C2M_JEMS.cif'),
              (out/'raw_xrd_03/LFNSO21-B_profile.csv','inputs/LFNSO21-B_profile.csv'),
              (Path('/workspace/lfnso-data/raw_xrd/LFSO_LFNSO21 XRD data.xlsx'),'inputs/LFSO_LFNSO21 XRD data.xlsx')])
# Validate inputs before replacing any archive generated by this script.
for p,_ in files:
    if not p.is_file():
        raise FileNotFoundError(p)
extra = {}
for src,dest in [('occupational_search.json','occupational_search_02'),('occupational_search_full_superstructure.json','occupational_search_03')]:
    c = json.loads((root/'configs'/src).read_text())
    c.update(template='inputs/Li2MnO3_C2M_JEMS.cif',experimental_csv='inputs/LFNSO21-B_profile.csv',output='../reproduced/'+dest)
    extra['portable_configs/'+src] = (json.dumps(c,indent=2)+'\n').encode()
c = json.loads((root/'configs/occupational_assessment.json').read_text())
c.update(experimental_csv='inputs/LFNSO21-B_profile.csv',output='../reproduced/assessment_01',sources=['../reproduced/occupational_search_02','../reproduced/occupational_search_03'])
extra['portable_configs/occupational_assessment.json'] = (json.dumps(c,indent=2)+'\n').encode()
extra['REPRODUCE.txt'] = '''LFNSO21-B occupancy search: provisional structures, not validated crystal models.
Latest review: 03_structure_model_search/occupational_assessment_03/report.html
See docs/OCCUPATIONAL_SEARCH.md for assumptions, scores, and limitations.

From the extracted root, with Python 3.12:
python -m pip install -r requirements.lock.txt
python -m pip install --no-deps -e .
python -m lfnso.occupational_search portable_configs/occupational_search.json
python -m lfnso.occupational_search portable_configs/occupational_search_full_superstructure.json
python -m lfnso.occupational_assessment portable_configs/occupational_assessment.json

Portable runs write to reproduced/ and preserve the bundled results.
Original cloud configs/checkpoints remain under configs/ and 03_structure_model_search/.
The supplied CIF, XRD workbook and derived B numeric profile are bundled in inputs/.
Microscopy originals are not included. SHA256SUMS.json covers every bundled file except itself.
'''.encode()
manifest = {}
staging = archive.with_suffix('.zip.tmp')
with zipfile.ZipFile(staging,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
    for p,name in files:
        content = p.read_bytes()
        manifest[name] = hashlib.sha256(content).hexdigest()
        z.writestr(name,content)
    for name,content in extra.items():
        manifest[name] = hashlib.sha256(content).hexdigest()
        z.writestr(name,content)
    z.writestr('SHA256SUMS.json',json.dumps(manifest,indent=2))
with zipfile.ZipFile(staging) as z:
    assert z.testzip() is None
    assert len([n for n in z.namelist() if n.endswith('/model.cif')]) == 20
    for name,sha in manifest.items():
        assert hashlib.sha256(z.read(name)).hexdigest() == sha
staging.replace(archive)
print(json.dumps({'archive':str(archive),'bytes':archive.stat().st_size,'hashed_files':len(manifest),'CIFs':20},indent=2))
